#!/usr/bin/env python3
"""Build the deployable GitHub Pages files from the canonical source.

Repository layout:
  src/tracker-source.html   canonical application source (edit THIS file)
  src/sw.js                 authored service worker source (edit THIS file)
  index.html                GENERATED by this script - do not hand-edit
  sw.js                     GENERATED copy of src/sw.js - do not hand-edit

The build applies exactly four scripted changes to the source:
  1. BASEMAP_MODE 'raster' -> 'vector'
  2. MapLibre GL CSS injected after the Leaflet CSS link
  3. MapLibre GL JS + maplibre-gl-leaflet plugin injected after the Leaflet JS tag
  4. a Content-Security-Policy <meta> stamped by scripts/csp_stamp.py, whose
     script/style hashes are computed from the transformed bundle itself
and copies src/sw.js to sw.js. It then verifies:
  * parity  - reversing the four changes reproduces the source byte-for-byte,
              so any other source/deployment difference fails the build
  * SEC-10a - the service worker's CORE integrity hashes and URLs equal the
              deployed page tags' (the two copies of the SRI data cannot drift)
  * CSP     - the bundle's stamped policy exactly matches a fresh hash
              computation over the bundle's own inline script/style, so a
              code change can never ship under a stale policy

Usage:
  python3 scripts/build-pages.py           build + verify (writes index.html, sw.js)
  python3 scripts/build-pages.py --check   verify only: fails if the committed
                                           index.html / sw.js differ from a fresh
                                           build (used by CI; writes nothing)

Standard library only; no dependencies.
"""
import hashlib
import re
import sys
from pathlib import Path

import csp_stamp

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / 'src' / 'tracker-source.html'
SW_SRC = REPO / 'src' / 'sw.js'
OUT_INDEX = REPO / 'index.html'
OUT_SW = REPO / 'sw.js'

LEAFLET_CSS = '<link rel="stylesheet" href="https://unpkg.com/leaflet@1.9.4/dist/leaflet.css" integrity="sha384-sHL9NAb7lN7rfvG5lfHpm643Xkcjzp4jFvuavGOndn6pjVqS6ny56CAt3nsEVT4H" crossorigin="anonymous">'
GL_CSS = '<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/maplibre-gl@4.7.1/dist/maplibre-gl.css" integrity="sha384-MinO0mNliZ3vwppuPOUnGa+iq619pfMhLVUXfC4LHwSCvF9H+6P/KO4Q7qBOYV5V" crossorigin="anonymous">'
LEAFLET_JS = '<script src="https://unpkg.com/leaflet@1.9.4/dist/leaflet.js" integrity="sha384-cxOPjt7s7Iz04uaHJceBmS+qpjv2JkIHNVcuOrM+YHwZOmJGBXI00mdUXEq65HTH" crossorigin="anonymous"></script>'
GL_JS = ('<script src="https://cdn.jsdelivr.net/npm/maplibre-gl@4.7.1/dist/maplibre-gl.js" integrity="sha384-SYKAG6cglRMN0RVvhNeBY0r3FYKNOJtznwA0v7B5Vp9tr31xAHsZC0DqkQ/pZDmj" crossorigin="anonymous"></script>\n'
         '<script src="https://cdn.jsdelivr.net/gh/maplibre/maplibre-gl-leaflet@v0.0.22/leaflet-maplibre-gl.js" integrity="sha384-4CB9Vtol9LN6lGgBCvmPLbUEZwilrqIvPieSRurgAXAB7FVJaLS9n8WyAIA5wjQ+" crossorigin="anonymous"></script>')


def build(src_text: str) -> str:
    s = src_text
    for needle in ("const BASEMAP_MODE = 'raster';", LEAFLET_CSS, LEAFLET_JS):
        assert s.count(needle) == 1, f'anchor not unique/found: {needle[:60]} (count={s.count(needle)})'
    s = s.replace("const BASEMAP_MODE = 'raster';", "const BASEMAP_MODE = 'vector';")
    s = s.replace(LEAFLET_CSS, LEAFLET_CSS + '\n' + GL_CSS)
    s = s.replace(LEAFLET_JS, LEAFLET_JS + '\n' + GL_JS)
    assert s.count("BASEMAP_MODE = 'vector'") == 1
    assert s.count('maplibre-gl-leaflet@v0.0.22') == 1
    # The stamp goes on LAST: its hashes cover the transformed bundle's own
    # inline script/style, exactly as the browser will receive them.
    return csp_stamp.apply_stamp(s)


def verify(bundle: str, src_text: str, sw_text: str) -> None:
    stamped = csp_stamp.stamped_policy(bundle)
    assert stamped is not None, 'CSP FAIL: bundle carries no Content-Security-Policy meta'
    assert stamped == csp_stamp.compute_policy(bundle), 'CSP FAIL: stamped policy does not match the bundle code - stale stamp'
    print('CSP check: PASS (stamped policy hash matches the bundle\'s own script/style)')
    r = csp_stamp.strip_stamp(bundle)
    r = r.replace("const BASEMAP_MODE = 'vector';", "const BASEMAP_MODE = 'raster';")
    r = r.replace(LEAFLET_CSS + '\n' + GL_CSS, LEAFLET_CSS)
    r = r.replace(LEAFLET_JS + '\n' + GL_JS, LEAFLET_JS)
    assert r == src_text, 'PARITY FAIL: index.html differs from source beyond the 4 known build edits'
    print('parity check: PASS (index.html == source + the 4 known build edits, nothing else)')
    tag_hashes = set(re.findall(r'integrity="(sha384-[^"]+)"', bundle))
    core_pairs = re.findall(r"\['(https://[^']+)', '(sha384-[^']+)'\]", sw_text)
    assert len(core_pairs) == 5, f'SEC-10a: expected 5 CORE pairs in sw.js, found {len(core_pairs)}'
    assert set(h for _, h in core_pairs) == tag_hashes, 'SEC-10a FAIL: sw.js CORE hashes differ from the page tags - SRI drift'
    tag_urls = set(re.findall(r'(?:src|href)="(https://[^"]+)"[^>]*integrity=', bundle))
    assert set(u for u, _ in core_pairs) == tag_urls, 'SEC-10a FAIL: sw.js CORE urls differ from the page tags'
    print('SEC-10a check: PASS (sw.js CORE == page tags, 5 urls + hashes)')


def main() -> int:
    check_only = '--check' in sys.argv[1:]
    src_text = SRC.read_text(encoding='utf-8')
    sw_text = SW_SRC.read_text(encoding='utf-8')
    bundle = build(src_text)
    verify(bundle, src_text, sw_text)
    if check_only:
        ok = True
        if OUT_INDEX.read_text(encoding='utf-8') != bundle:
            print('CHECK FAIL: index.html differs from a fresh build')
            ok = False
        if OUT_SW.read_text(encoding='utf-8') != sw_text:
            print('CHECK FAIL: sw.js differs from src/sw.js')
            ok = False
        if not ok:
            return 1
        print('check: PASS (committed index.html and sw.js match a fresh build)')
        return 0
    OUT_INDEX.write_text(bundle, encoding='utf-8')
    OUT_SW.write_text(sw_text, encoding='utf-8')
    data = bundle.encode()
    print('index.html:', len(data), 'bytes, SHA-256', hashlib.sha256(data).hexdigest())
    print('sw.js: copied from src/sw.js')
    return 0


if __name__ == '__main__':
    sys.exit(main())
